namespace Interior
{
    /// <summary>
    /// Нумерация розеток корабля: каждая запись — одна ручка одного устройства.
    ///
    /// Это не список дел устройства — тот живёт в самом устройстве, в его Wire(), рядом с
    /// кодом, который эти дела исполняет. Здесь только адреса, и они общие, потому что щиток
    /// ищет по одному ключу.
    ///
    /// Номера проставлены руками и не переиспользуются. В ассете разъёма лежит число, а не
    /// имя, поэтому вставка записи в середину без явных номеров перевесила бы половину панели
    /// на чужие дела — молча. Удалили запись — её номер остаётся дыркой навсегда. Переименовать
    /// запись, наоборот, безопасно: номер тот же.
    ///
    /// Номера раздаются блоками по сотне на устройство. Сегодня это только читаемость: видно,
    /// чьё дело, и видно, когда устройство раздулось. Но если однажды у корабля окажется два
    /// одинаковых агрегата, адресовать их плоским перечнем станет нечем, и перечень придётся
    /// разрезать на «какая ручка у устройства» — резать будут ровно по этим границам.
    ///
    /// None — состояние «ассет создан, но ни к чему не привязан». Щиток его не принимает.
    /// </summary>
    public enum CommandId
    {
        None = 0,

        // Двигатель — 100
        EngineToggle = 100,

        // Навигационный компьютер — 200
        NewManeuver = 200,
        ViewYawPlus = 201,
        ViewYawMinus = 202,
        ViewPitchPlus = 203,
        ViewPitchMinus = 204,
        KnobAccurateModeToggele = 205,
        RemoveManeuver = 206,
        NextManeuver = 207,
        NextTargetListItem = 208,
        PreviousTargetListItem = 209,
        SelectTarget = 210,
        ClearTarget = 211,
        TrackTargetListItem = 212,
        ShowTargetBodyList = 213,
        ShowManeuverList = 214,
        ManeuverLock = 215,
        ClearDeltaVX = 216,
        ClearDeltaVY = 217,
        ClearDeltaVZ = 218,
        FitView = 219,

        // Система ориентации — 300
        SasAxisX = 300,
        SasAxisY = 301,
        SasAxisZ = 302,
        SasAxisT = 303,
        SasAxisM = 304,
        SasDirPlus = 305,
        SasDirMinus = 306,
    }

    /// <summary>
    /// То, о чём устройства отвечают «да» или «нет». Правила и блоки те же, что у CommandId:
    /// одна сотня — одно устройство, номера не переиспользуются.
    /// </summary>
    public enum SignalId
    {
        None = 0,

        // Двигатель — 100
        EngineRunning = 100,

        // Навигационный компьютер — 200
        ManeuverPlanned = 200,
        DeltaVRemaining = 201,
        KnobAccurateModeEnabled = 202,
        Maneuver1Created = 203,
        Maneuver2Created = 204,
        Maneuver3Created = 205,
        ManeuverLocked = 206,
    }

    /// <summary>
    /// Ручки, которые крутят. Крутилка отдаёт только знак и счёт — «щёлкнули в плюс», —
    /// а насколько это много, решает устройство: шаг по Δv равен проценту текущей орбитальной
    /// скорости, и знает его только корабль. Положить такой шаг в ассет нельзя, он меняется
    /// каждую секунду полёта.
    ///
    /// Блоки и правила нумерации — как у CommandId.
    /// </summary>
    public enum StepId
    {
        None = 0,

        // Навигационный компьютер — 200
        NavRange = 200,
        ManeuverTime = 201,
        DeltaVX = 202,
        DeltaVY = 203,
        DeltaVZ = 204,
    }

    /// <summary>
    /// Величины, которые орган выставляет целиком. Рычаг тяги не щёлкает, а стоит: доля
    /// хода — это и есть значение, и оно абсолютное, поэтому крутилкой его не передать.
    ///
    /// От показания отличается направлением: показание устройство отдаёт, величину —
    /// принимает. Владеет ею всё равно устройство: рычаг её только выставляет, а снятый
    /// или сломанный орган не должен уносить тягу с собой.
    ///
    /// Блоки и правила нумерации — как у CommandId.
    /// </summary>
    public enum SettingId
    {
        None = 0,

        // Двигатель — 100
        Throttle = 100,
    }

    /// <summary>
    /// Числовые показания: одно число рядом с органом. Крутилка вслепую бесполезна —
    /// подкрутил Δv, а на сколько, не видно; показание и есть ответ на этот вопрос. Им же
    /// живёт стрелка на шкале, если такой орган появится: рукоятка не хранит значение,
    /// а отображает его.
    ///
    /// Только числа. Составные показания — несколько величин таблицей — остаются за экранами
    /// (ManeuverPanel, TargetListPanel, навигационный): разъём про одно число у одного органа.
    ///
    /// Блоки и правила нумерации — как у CommandId.
    /// </summary>
    public enum ReadingId
    {
        None = 0,

        // Двигатель — 100
        Acceleration = 100,
        RemainingBurn = 101,
        Throttle = 102,

        // Навигационный компьютер — 200
        NavRange = 200,
        TimeToNode = 201,
        DeltaVX = 202,
        DeltaVY = 203,
        DeltaVZ = 204,
        RemainingDeltaV = 205,
        ShipOrbitPereapsis = 206,
        ShipOrbitApoapsis = 207,
        ShipOrbitSemiMajorAxis = 208,
        ShipOrbitEccentricity = 209,
        ShipOrbitInclination = 210,
        ShipOrbitLongitudeOfAscendingNode = 211,
        ShipOrbitArgumentOfPeriapsis = 212,
    }
}
