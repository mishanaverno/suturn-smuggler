using UnityEngine;

namespace Interior
{
    /// <summary>
    /// Разъём — лицо одного дела кокпита: ассет, который перетаскивают в поле органа.
    ///
    /// Разделение труда такое. Enum (CommandId, SignalId) — источник правды: перечень того,
    /// что кокпит умеет, живёт в коде, потому что за каждым делом стоит написанный код.
    /// Ассет — то, что можно взять мышью: он несёт подпись у курсора и заметку, а связывает
    /// его с делом номер из enum. Ассеты не пишутся руками, их создаёт генератор по enum
    /// (меню Cockpit → Разъёмы).
    ///
    /// Поэтому орган на панели можно копировать, двигать, заменять другим префабом и
    /// перевешивать на другое дело, не заходя в код: код про конкретный кубик ничего не знает.
    ///
    /// В ассете лежат только данные. Ничего изменяемого в рантайме здесь хранить нельзя:
    /// ассет переживает выход из Play, и в следующем запуске старое состояние всплывёт.
    /// Всё живое — в ControlBus, он умирает вместе со сценой.
    /// </summary>
    public abstract class ControlPort : ScriptableObject
    {
        [Tooltip("Строка у курсора, когда игрок навёлся на орган. Глагол, а не название узла.")]
        public string displayName = "";

        [TextArea, Tooltip("Для себя: что это за дело и почему оно вынесено на панель.")]
        public string note = "";

        /// <summary>Привязан ли разъём к записи в enum. Пустой ассет ничем не управляет.</summary>
        public abstract bool Assigned { get; }

        /// <summary>Подпись органа. Пустое поле — не повод молчать: имя ассета тоже подпись.</summary>
        public string Title => string.IsNullOrEmpty(displayName) ? name : displayName;
    }
}
