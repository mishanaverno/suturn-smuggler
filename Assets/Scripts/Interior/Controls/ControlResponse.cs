using UnityEngine;

namespace Interior
{
    /// <summary>
    /// Отклик органа: то, что орган делает сам по себе, сработав. Ход кнопки, поворот ручки,
    /// щелчок, вспышка подсветки — всё, что видно и слышно, но ни на что не влияет.
    ///
    /// Отдельным компонентом, а не полями органа, по двум причинам. Во-первых, отклик —
    /// это «как выглядит», то есть вопрос глаз и сцены: большая кнопка ходит глубже и мягче,
    /// и это должно правиться мышью, а не заводить второй класс кнопки. Во-вторых, откликов
    /// может быть несколько сразу — ход, звук, лампочка подтверждения, — и они не обязаны
    /// знать друг о друге.
    ///
    /// Орган вызывает отклики только тогда, когда действие действительно прошло. Кнопка,
    /// нажатая вхолостую, не должна выглядеть нажатой.
    /// </summary>
    public abstract class ControlResponse : MonoBehaviour
    {
        public abstract void Play();

        /// <summary>
        /// Со знаком — для органов, у которых есть направление. По умолчанию направление
        /// игнорируется: кнопке оно ни к чему, а крутилке важно, в какую сторону повернуться.
        /// </summary>
        public virtual void Play(int direction) => Play();
    }
}
